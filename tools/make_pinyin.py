"""Generates the pinyin table used by search (src/core/pinyin_table.h).

Requires Python 3.8+ and a copy of pinyin-data (MIT licence):

    git clone https://github.com/mozillazg/pinyin-data

Usage:
    python tools/make_pinyin.py PATH_TO_PINYIN_DATA

The table covers the 3755 characters of GB2312 level 1, the most common Chinese
characters. The app finds a character's place in the table by converting it to
code page 936 (GBK, a superset of GB2312), so the table holds no code points.

Readings come from the Table of General Standard Chinese Characters (2013,
kTGHZ2013.txt), which lists every modern reading of a polyphone; characters it
lacks fall back to pinyin.txt. Tones are dropped and u-umlaut is written as v,
the way pinyin input methods type it. Each character keeps all its readings, so
"chongqing" and "zhongqing" both find 重庆.
"""

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "core" / "pinyin_table.h"

# GB2312 level 1: rows 0xB0-0xD7, 94 cells per row starting at 0xA1; row 0xD7 ends at 0xF9
FIRST_ROW, LAST_ROW, LAST_CELL = 0xB0, 0xD7, 0xF9


def gb2312_level1():
    chars = []
    for hi in range(FIRST_ROW, LAST_ROW + 1):
        for lo in range(0xA1, 0xFF):
            if hi == LAST_ROW and lo > LAST_CELL:
                break
            chars.append(bytes([hi, lo]).decode("gb2312"))
    return chars


def read_readings(path):
    """Reads "U+884C: háng,héng,xíng  # 行" lines into {char: [readings]}."""
    table = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        code, readings = line.split(":", 1)
        table[chr(int(code[2:], 16))] = [r.strip() for r in readings.split(",") if r.strip()]
    return table


def toneless(reading):
    s = unicodedata.normalize("NFD", reading.lower()).replace("ü", "v")
    return "".join(c for c in s if not unicodedata.combining(c))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = Path(sys.argv[1])
    standard = read_readings(data / "kTGHZ2013.txt")
    fallback = read_readings(data / "pinyin.txt")

    chars = gb2312_level1()
    readings = []
    for ch in chars:
        found = standard.get(ch) or fallback.get(ch)
        if not found:
            sys.exit(f"no reading for {ch} (U+{ord(ch):04X})")
        unique = []
        for r in map(toneless, found):
            if r not in unique:
                unique.append(r)
        readings.append(unique)

    syllables = sorted({r for rs in readings for r in rs})
    assert all(s.isascii() and s.isalpha() and len(s) <= 6 for s in syllables), syllables
    index = {s: i for i, s in enumerate(syllables)}
    first = [index[rs[0]] for rs in readings]
    more = [(i, index[r]) for i, rs in enumerate(readings) for r in rs[1:]]

    def rows(items, per_line):
        return "\n".join("    " + " ".join(items[i:i + per_line]) for i in range(0, len(items), per_line))

    OUT.write_text(
        "// Pinyin of the 3755 GB2312 level 1 characters, without tones. Generated by tools/make_pinyin.py\n"
        "// from pinyin-data (https://github.com/mozillazg/pinyin-data, MIT licence); do not edit.\n"
        "#pragma once\n\n"
        "#include <cstdint>\n\n"
        f"constexpr int kPinyinChars = {len(chars)};\n\n"
        "// Every toneless syllable, sorted; u-umlaut is written as v\n"
        f"constexpr char kSyllables[{len(syllables)}][7] = {{\n"
        + rows([f'"{s}",' for s in syllables], 12) + "\n};\n\n"
        "// The first reading of each character, by its place in GB2312 level 1\n"
        f"constexpr uint16_t kFirstReading[{len(first)}] = {{\n"
        + rows([f"{v}," for v in first], 16) + "\n};\n\n"
        "// The other readings of polyphones: {place, syllable}, sorted by place\n"
        f"constexpr uint16_t kMoreReadings[{len(more)}][2] = {{\n"
        + rows([f"{{{i}, {s}}}," for i, s in more], 8) + "\n};\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(chars)} characters, {len(syllables)} syllables, "
          f"{len(more)} extra readings")


if __name__ == "__main__":
    main()
